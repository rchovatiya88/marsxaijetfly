#!/usr/bin/env node
'use strict';
// Run only after the corresponding Blender scene has been saved and reviewed.
// Generated TS literals keep browser data and the authored JSON in agreement
// without adding runtime JSON fetches or changing the test module loader.
const fs=require('node:fs');
const layout=JSON.parse(fs.readFileSync('art/bridgehead/bridgehead-v2-layout.json','utf8'));
const source='src/mission/bridgehead-run.ts';
const current=fs.readFileSync(source,'utf8');
const helperStart=current.indexOf('export function crossesXGate');
if (helperStart<0 || layout.version!==2) throw Error('Unexpected mission source or authoring version');
const literal=value=>JSON.stringify(value,null,2);
const declaration=(name,value,type='')=>`export const ${name}${type?`: ${type}`:''} = ${literal(value)}${type?'':' as const'};`;
const declarations=[
  declaration('BRIDGEHEAD_LAYOUT_VERSION',layout.version),
  declaration('BRIDGEHEAD_ENVIRONMENT_SCALE',layout.environmentScale),
  declaration('BRIDGEHEAD_SPEED',layout.movement.speed),
  declaration('BRIDGEHEAD_BOOST_SPEED',layout.movement.boost),
  declaration('BRIDGEHEAD_CAMERA',layout.camera),
  declaration('BRIDGEHEAD_PLAYER_ENVELOPE',layout.player.bodyEnvelope),
  declaration('BRIDGEHEAD_START',layout.start,'Vec'),
  declaration('BRIDGEHEAD_HIGH_APPROACH',layout.highApproach),
  declaration('BRIDGEHEAD_HIGH_DESCENT',layout.highDescent),
  declaration('BRIDGEHEAD_HIGH_ALIGN',layout.highAlign),
  declaration('BRIDGEHEAD_LOW_CLIMB',layout.lowClimb),
  declaration('BRIDGEHEAD_HIGH_CLIMB',layout.highClimb),
  declaration('BRIDGEHEAD_GATES',layout.gates),
  declaration('BRIDGEHEAD_EXITS',layout.exits),
  declaration('BRIDGEHEAD_APPROACHES',layout.approaches),
  declaration('BRIDGEHEAD_LOW_PEEK',layout.lowPeek,'Vec'),
  declaration('BRIDGEHEAD_HIGH_DODGE',layout.highDodge,'Vec'),
  declaration('BRIDGEHEAD_WARDEN',layout.warden,'Vec'),
  declaration('BRIDGEHEAD_EXTRACTION',layout.extraction,'Vec'),
  declaration('BRIDGEHEAD_EXTRACTION_RADIUS',layout.extractionRadius),
  declaration('BRIDGEHEAD_WORLD',layout.world,'WorldDefinition'),
  declaration('BRIDGEHEAD_ROUTE_PATHS',layout.routePaths,'Record<BridgeheadRoute, Vec[]>'),
  declaration('BRIDGEHEAD_EXTRACTION_PATH',layout.extractionPath,'Vec[]'),
  declaration('BRIDGEHEAD_COMBAT',layout.combat)
];
const result=`import type { Vec, WorldDefinition } from '../arena-world';\n\nexport type BridgeheadRoute = 'high' | 'low';\n\n// Generated by scripts/sync-bridgehead-layout.cjs from the saved Blender contract.\n${declarations.join('\n\n')}\n\n${current.slice(helperStart)}`;
if(process.argv.includes('--check')) {
  if(result!==current) {console.error('Bridgehead TS differs from the authored layout JSON.');process.exitCode=1;}
  else console.log('Bridgehead TS matches the authored layout JSON.');
} else {fs.writeFileSync(source,result);console.log(`Updated ${source} from authored layout v${layout.version}.`);}
